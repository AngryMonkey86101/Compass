const A_WGS84 = 6378.137; // большая полуось эллипсоида, км
const F_WGS84 = 1 / 298.257223563;
const E2 = F_WGS84 * (2 - F_WGS84);
const R_REF = 6371.2; // опорный радиус модели, км
const RAD = Math.PI / 180;

// Коэффициенты, умноженные на множители Шмидта, и коэффициенты рекурсии полиномов Лежандра.
// Строятся один раз при первом расчёте.
let model = null;

function buildModel() {
  const rows = [];
  let schmidtN0 = 1;
  let i = 0;
  for (let n = 1; n <= N_MAX; n++) {
    schmidtN0 *= (2 * n - 1) / n;
    let schmidt = schmidtN0;
    const row = [];
    for (let m = 0; m <= n; m++) {
      if (m > 0) schmidt *= Math.sqrt(((n - m + 1) * (m === 1 ? 2 : 1)) / (n + m));
      const [g, h, gDot, hDot] = COEFFS[i++];
      row.push({
        g: g * schmidt,
        h: h * schmidt,
        gDot: gDot * schmidt,
        hDot: hDot * schmidt,
        k: n > 1 ? ((n - 1) * (n - 1) - m * m) / ((2 * n - 1) * (2 * n - 3)) : 0
      });
    }
    rows.push(row);
  }
  return rows;
}

// Год с дробной частью: 1 июля 2026 → ~2026.5
export function decimalYear(date) {
  const year = date.getUTCFullYear();
  const start = Date.UTC(year, 0, 1);
  return year + (date.getTime() - start) / (Date.UTC(year + 1, 0, 1) - start);
}

// Вектор поля в нТл: x — на север, y — на восток, z — вниз. lat, lon — градусы (WGS84),
// altKm — высота над эллипсоидом, year — год с дробной частью.
export function geomagneticField(lat, lon, altKm, year) {
  if (!model) model = buildModel();
  const dt = Math.min(Math.max(year, EPOCH), VALID_UNTIL) - EPOCH;

  // геодезические координаты → геоцентрические
  const phi = lat * RAD;
  const sinPhi = Math.sin(phi);
  const cosPhi = Math.cos(phi);
  const rc = A_WGS84 / Math.sqrt(1 - E2 * sinPhi * sinPhi);
  const p = (rc + altKm) * cosPhi;
  const z = (rc * (1 - E2) + altKm) * sinPhi;
  const r = Math.sqrt(p * p + z * z);
  const phiC = Math.asin(z / r);
  const cosTheta = Math.sin(phiC); // θ — геоцентрическое дополнение широты
  const sinTheta = Math.cos(phiC);

  // присоединённые полиномы Лежандра (нормировка Гаусса) и их производные по θ
  const P = [[1]];
  const dP = [[0]];
  let xs = 0;
  let ys = 0;
  let zs = 0;
  const ratio = R_REF / r;
  let radial = ratio * ratio;
  const lam = lon * RAD;
  for (let n = 1; n <= N_MAX; n++) {
    radial *= ratio; // (R_REF / r)^(n + 2)
    P.push([]);
    dP.push([]);
    for (let m = 0; m <= n; m++) {
      const c = model[n - 1][m];
      if (m === n) {
        P[n][m] = sinTheta * P[n - 1][m - 1];
        dP[n][m] = sinTheta * dP[n - 1][m - 1] + cosTheta * P[n - 1][m - 1];
      } else {
        const p2 = m <= n - 2 ? P[n - 2][m] : 0;
        const dp2 = m <= n - 2 ? dP[n - 2][m] : 0;
        P[n][m] = cosTheta * P[n - 1][m] - c.k * p2;
        dP[n][m] = cosTheta * dP[n - 1][m] - sinTheta * P[n - 1][m] - c.k * dp2;
      }
      const g = c.g + dt * c.gDot;
      const h = c.h + dt * c.hDot;
      const cosM = Math.cos(m * lam);
      const sinM = Math.sin(m * lam);
      const along = g * cosM + h * sinM;
      xs += radial * along * dP[n][m];
      ys += radial * m * (g * sinM - h * cosM) * P[n][m];
      zs -= radial * (n + 1) * along * P[n][m];
    }
  }
  ys /= sinTheta;

  // из геоцентрической системы в геодезическую (поворот на разницу широт)
  const psi = phiC - phi;
  return {
    x: xs * Math.cos(psi) - zs * Math.sin(psi),
    y: ys,
    z: xs * Math.sin(psi) + zs * Math.cos(psi)
  };
}

// Склонение в градусах: плюс — восточное (магнитный север правее истинного), минус — западное.
// Истинный азимут = магнитный + склонение. На полюсах направление на север не определено,
// поэтому широта ограничена ±89.9°.
export function magneticDeclination(lat, lon, date = new Date()) {
  const safeLat = Math.min(Math.max(lat, -89.9), 89.9);
  const { x, y } = geomagneticField(safeLat, lon, 0, decimalYear(date));
  return Math.atan2(y, x) / RAD;
}

// +14,3° / −7,0°
export const formatDeclination = (deg) =>
  `${deg < 0 ? '−' : '+'}${Math.abs(deg).toFixed(1).replace('.', ',')}°`;
